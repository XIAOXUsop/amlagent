package com.bank.aml.common.enums;

/**
 * 工单生命周期状态。
 */
public enum CaseStatus {

    /** 待处理（已创建，任务待执行）。注意：也可能是“已入队尚未领取”，前端在无任务状态可查时只显示待处理。 */
    PENDING,
    /** 执行中 */
    RUNNING,
    /** 最终结案：仅来自人工排除预警、报送完成或存量兼容案件的自动完成；调查契约 v1 案件不会自动进入。 */
    DONE,
    /** 人工处理中：命中底线规则转人工，或调查契约 v1 要求人工最终处置（待补齐调查或待复核决定）。 */
    HOLD,
    /** 已确认可疑，等待完成可疑交易报告报送。 */
    REPORT_PENDING,
    /** 执行失败 */
    FAILED,
    /** 重试等待（可重试失败后，按指数退避等待重新入队） */
    RETRY_WAIT

}
